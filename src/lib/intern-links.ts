const byEmployeeId = new Map<string, InternLinkRecord>();
const byEmail = new Map<string, InternLinkRecord>();
const byToken = new Map<string, InternLinkRecord>();

for (const record of PERMANENT_INTERN_LINKS) {
  byEmployeeId.set(record.employeeId.toUpperCase(), record);
  byEmail.set(record.email.toLowerCase(), record);
  byToken.set(record.token, record);
}

/**
 * Returns the permanent direct upload URL for an intern by employeeId, email, or token.
 */
export function getPermanentLinkForIntern(identifier: string): string | null {
  if (!identifier) return null;
  const clean = identifier.trim();
  const match =
    byEmployeeId.get(clean.toUpperCase()) ||
    byEmail.get(clean.toLowerCase()) ||
    byToken.get(clean);
  return match ? match.directLink : null;
}

/**
 * Returns the full intern link record by employeeId, email, or token.
 */
export function getPermanentRecordForIntern(identifier: string): InternLinkRecord | null {
  if (!identifier) return null;
  const clean = identifier.trim();
  return (
    byEmployeeId.get(clean.toUpperCase()) ||
    byEmail.get(clean.toLowerCase()) ||
    byToken.get(clean) ||
    null
  );
}
